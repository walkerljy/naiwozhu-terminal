def _set_para(paragraph, new):
    """替换段落文字，保留首个 run 的格式。"""
    runs = paragraph.runs
    if not runs:
        return False
    runs[0].text = new
    for r in runs[1:]:
        r.text = ""
    return True


def replace(slide_no, old, new):
    """在第 N 页（1 起）找正文/表格里完全等于 old 的段落并替换。"""
    slide = prs.slides[slide_no - 1]
    for sh in slide.shapes:
        if sh.has_text_frame:
            for p in sh.text_frame.paragraphs:
                if "".join(r.text for r in p.runs).strip() == old:
                    return _set_para(p, new)
        if sh.has_table:
            for row in sh.table.rows:
                for cell in row.cells:
                    for p in cell.text_frame.paragraphs:
                        if "".join(r.text for r in p.runs).strip() == old:
                            return _set_para(p, new)
    return False


def replace_note(slide_no, old, new):
    """讲稿是整段一个段落，必须做子串替换——整段覆盖会把讲解内容吞掉。"""
    slide = prs.slides[slide_no - 1]
    if not slide.has_notes_slide:
        return False
    for p in slide.notes_slide.notes_text_frame.paragraphs:
        full = "".join(r.text for r in p.runs)
        if old in full:
            runs = p.runs
            runs[0].text = full.replace(old, new)
            for r in runs[1:]:
                r.text = ""
            return True
    return False


